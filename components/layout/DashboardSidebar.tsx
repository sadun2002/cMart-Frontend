interface NavItem {
  href: string;
  label: string;
  icon: string;
}

interface DashboardSidebarProps {
  navItems: readonly NavItem[];
  role: 'admin' | 'owner' | 'employee';
}

export default function DashboardSidebar({ navItems, role }: DashboardSidebarProps) {
  const pathname = usePathname();
  const { user, logout } = useAuthStore();
  const router = useRouter();
  const [collapsed, setCollapsed] = useState(false);

  const handleLogout = () => {
    logout();
    toast.success('Signed out successfully');
    router.push('/login');
  };

  const roleBadgeColor = {
    admin: 'bg-purple-500',
    owner: 'bg-blue-500',
    employee: 'bg-green-500',
  }[role];

  const roleLabel = {
    admin: 'Super Admin',
    owner: 'Store Owner',
    employee: 'Employee',
  }[role];

  return (
    <aside className={`sidebar ${collapsed ? 'collapsed' : ''} flex-shrink-0`}>
      {/* Logo */}
      <div className="px-4 py-5 border-b border-border flex items-center justify-between">
        {!collapsed && (
          <div className="flex items-center gap-2.5">
            <img src="/logo-small.png" alt="cMart Logo" className="w-8 h-8 object-contain rounded-[10px] shadow-sm shadow-blue-200" />
            <span className="text-foreground font-black text-lg tracking-tight">cMart</span>
          </div>
        )}
        {collapsed && (
          <img src="/logo-small.png" alt="cMart Logo" className="w-8 h-8 object-contain mx-auto rounded-[10px] shadow-sm shadow-blue-200" />
        )}
        {!collapsed && (
          <button
            onClick={() => setCollapsed(true)}
            className="text-muted-foreground hover:text-foreground transition-colors"
          >
            <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M11 19l-7-7 7-7m8 14l-7-7 7-7" />
            </svg>
          </button>
        )}
        {collapsed && (
          <button
            onClick={() => setCollapsed(false)}
            className="text-muted-foreground hover:text-foreground transition-colors absolute right-2 top-6"
          >
            <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M13 5l7 7-7 7M5 5l7 7-7 7" />
            </svg>
          </button>
        )}
      </div>

      {/* User info */}
      {!collapsed && (
        <div className="px-4 py-3 border-b border-border">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-full bg-gradient-to-br from-blue-100 to-blue-50 dark:from-blue-900/40 dark:to-blue-800/20 flex items-center justify-center text-blue-600 dark:text-blue-400 text-sm font-semibold flex-shrink-0">
              {user?.name?.[0]?.toUpperCase() || 'U'}
            </div>
            <div className="min-w-0">
              <p className="text-foreground text-sm font-medium truncate">{user?.name || 'User'}</p>
              <div className="flex items-center gap-1.5">
                <span className={`inline-block w-1.5 h-1.5 rounded-full ${roleBadgeColor}`} />
                <span className="text-muted-foreground text-xs">{roleLabel}</span>
              </div>
            </div>
          </div>
          {user?.tenant && (
            <div className="mt-2 text-xs text-muted-foreground truncate">
              {user.tenant.businessName}
            </div>
          )}
        </div>
      )}

      {/* Navigation */}
      <nav className="flex-1 overflow-y-auto py-3 no-scrollbar">
        {navItems.map((item) => {
          const isActive = pathname === item.href || pathname.startsWith(item.href + '/');
          return (
            <Link
              key={item.href}
              href={item.href}
              title={collapsed ? item.label : undefined}
              className={`sidebar-nav-item ${isActive ? 'active' : ''} ${collapsed ? 'justify-center px-0 mx-2' : ''}`}
            >
              <span className="flex-shrink-0">{icons[item.icon] || icons.LayoutDashboard}</span>
              {!collapsed && <span>{item.label}</span>}
            </Link>
          );
        })}
      </nav>

      {/* Logout */}
      <div className="p-4 border-t border-border mt-auto">
        <button
          onClick={handleLogout}
          className={`w-full flex items-center gap-2 text-muted-foreground hover:text-foreground transition-colors text-sm py-2 px-2 rounded-lg hover:bg-muted ${collapsed ? 'justify-center' : ''}`}
        >
          <svg className="w-4 h-4 flex-shrink-0" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
          </svg>
          {!collapsed && <span>Sign Out</span>}
        </button>
      </div>
    </aside>
  );
}
